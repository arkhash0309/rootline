"""Render files that cannot read versions.yaml directly (GEN-050).

Outputs:
  deploy/root/files/versions.yaml  - subset consumed by the root Helm chart
  .github/versions.env             - KEY=VALUE lines for GitHub Actions ($GITHUB_ENV)
  deploy/charts/observability/Chart.yaml - `dependencies[].version` rewritten to the `chart` value of
                                     the same-named versions.yaml key (every other line is kept)
  deploy/charts/platform-config/files/versions.yaml - the rows of PLATFORM_CONFIG_KEYS, written only
                                     when deploy/charts/platform-config/Chart.yaml exists (ADR 0046 T11)
Usage: uv run python scripts/render_versions.py [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.versions_lib import REPO, load_versions, version_of

CHART_KEYS = [
    "argo-cd",
    "kube-prometheus-stack",
    "prometheus-operator-crds",
    "loki",
    "tempo",
    "opentelemetry-collector",
    "chaos-mesh",
    "kyverno",
    "external-secrets",
    "cert-manager",
    "cloudnative-pg",
    "traefik",
    "keycloak",
    "keycloak-config-cli",
    "gateway-api",
    "opa-image",
    "busybox",
]
# Rows of versions.yaml read by chart `platform-config` (copy-ca image, ADR 0046 T11).
PLATFORM_CONFIG_KEYS = ["kubectl-image"]
# Wrapper charts whose `dependencies[].version` values are generated (GEN-050).
DEPENDENCY_CHART_FILES = [REPO / "deploy/charts/observability/Chart.yaml"]
DEPENDENCY_NAME_RE = re.compile(r"^\s*-\s+name:\s*(\S+)\s*$")
DEPENDENCY_VERSION_RE = re.compile(r"^(\s+version:\s*)(\S+?)(\s*)$")
ENV_KEYS = [
    "python",
    "node",
    "uv",
    "opa",
    "terraform",
    "kind",
    "kubeconform",
    "tflint",
    "trivy",
    "gitleaks",
    "kyverno-cli",
    "cosign",
    "syft",
    "playwright",
    "k3s",
]


def rewrite_chart_dependencies(text: str, data: dict[str, Any]) -> str:
    """Return `text` (a Chart.yaml) with each dependency `version` set from versions.yaml.

    A `version:` line belongs to the dependency named by the closest preceding `- name: <key>` line
    of the `dependencies:` list; the new value is `data[<key>]["chart"]`, double-quoted. Lines of
    dependencies whose name is not a versions.yaml key are kept unchanged. Raises `KeyError` when a
    dependency key has no `chart` value.
    """
    out: list[str] = []
    in_dependencies = False
    current: str | None = None
    for line in text.splitlines(keepends=True):
        stripped = line.rstrip("\r\n")
        if stripped == "dependencies:":
            in_dependencies = True
        elif stripped and not stripped[0].isspace() and not stripped.startswith("#"):
            in_dependencies = False
            current = None
        if in_dependencies:
            name = DEPENDENCY_NAME_RE.match(stripped)
            if name:
                current = name.group(1)
            version = DEPENDENCY_VERSION_RE.match(stripped)
            if version and current in data:
                line = (
                    f'{version.group(1)}"{data[current]["chart"]}"{version.group(3)}' + line[len(stripped) :]
                )
        out.append(line)
    return "".join(out)


def render() -> dict[Path, str]:
    data = load_versions()
    charts = {k: data[k] for k in CHART_KEYS if k in data}
    out_yaml = (
        "# GENERATED by scripts/render_versions.py from versions.yaml. Do not edit.\n"
        + yaml.safe_dump(charts, sort_keys=True)
    )
    env_lines = ["# GENERATED by scripts/render_versions.py from versions.yaml. Do not edit."]
    for k in ENV_KEYS:
        env_lines.append(f"V_{k.upper().replace('-', '_')}={version_of(k, data)}")
    files = {
        REPO / "deploy/root/files/versions.yaml": out_yaml,
        REPO / ".github/versions.env": "\n".join(env_lines) + "\n",
    }
    for chart_file in DEPENDENCY_CHART_FILES:
        if chart_file.exists():
            files[chart_file] = rewrite_chart_dependencies(chart_file.read_text(encoding="utf-8"), data)
    if (REPO / "deploy/charts/platform-config/Chart.yaml").exists():
        files[REPO / "deploy/charts/platform-config/files/versions.yaml"] = (
            "# GENERATED by scripts/render_versions.py from versions.yaml. Do not edit.\n"
            + yaml.safe_dump({k: data[k] for k in PLATFORM_CONFIG_KEYS}, sort_keys=True)
        )
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    stale = []
    for path, content in render().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            if args.check:
                stale.append(str(path.relative_to(REPO)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("stale generated files: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
