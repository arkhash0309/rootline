"""Derive the WKL-031 alert thresholds from the WKL-004 baseline samples (W1-T13).

Usage:
  uv run python scripts/derive_thresholds.py --samples data/baseline/<date>/samples.json \\
      [--out deploy/values/alert-thresholds.yaml] \\
      [--chart-copy deploy/charts/observability/files/alert-thresholds.yaml]

Input file (written by `scripts/baseline_gate.py`): JSON
`{"date": "YYYY-MM-DD", "samples": {<key>: [float, ...]}}` where `<key>` is `latency_p95:<service>` (seconds, 15 s range-query points) or `kafka_consumer_lag:<service>`
(records). Non-finite points (NaN, +Inf, -Inf: no traffic in the window) are dropped.

Formulas (WKL-031, dagger thresholds):

| Output key | Formula |
|---|---|
| `baseline_p95[svc]` | 95th percentile of the finite `latency_p95:<svc>` points (linear interpolation, as `numpy.percentile`), rounded to 4 decimals; `0.0` without a finite point |
| `ServiceHighLatency[svc]` | `max(1.0, round(3 * baseline_p95[svc], 4))` |
| `KafkaConsumerLagHigh[svc]` | `max(1000.0, round(10 * p95(lag points), 4))`; `1000.0` without a finite point |

The percentile is computed in pure Python: `numpy` is not a dependency of the workspace (ADR 0049 D5).

Outputs: the values file and a byte-identical copy in the chart `files/` directory (the chart reads it with
`.Files.Get`). The first line of both is
`# GENERATED by scripts/derive_thresholds.py from the WKL-004 baseline run on <date>. Do not edit.`

Exit codes: 0 both files written; 2 unreadable or malformed samples file, an unknown sample key (nothing
written), or an `OSError` while writing an output (for example a target directory that is a file or is not
writable). The text is rendered once, both outputs are first written to `<target>.tmp` and only then renamed over
the targets: a failure while writing the temporary files leaves both targets unchanged; a rename failure after
that can leave the first target updated, and the run exits 2 and must be repeated. The message
`derive_thresholds: cannot write the outputs: <error>` goes to stderr.
"""  # noqa: E501 - markdown tables in the module docstring

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO / "deploy/values/alert-thresholds.yaml"
DEFAULT_CHART_COPY = REPO / "deploy/charts/observability/files/alert-thresholds.yaml"
LATENCY_FLOOR_S = 1.0  # WKL-031 ServiceHighLatency: max(1.0, 3 x baseline p95)
LATENCY_FACTOR = 3.0
LAG_FLOOR = 1000.0  # WKL-031 KafkaConsumerLagHigh: max(1000, 10 x baseline)
LAG_FACTOR = 10.0
PERCENTILE = 95.0


def percentile(values: list[float], q: float) -> float:
    """`q`-th percentile of `values` by linear interpolation (numpy default); ValueError when empty."""
    if not values:
        raise ValueError("percentile of an empty list")
    ordered = sorted(values)
    rank = (len(ordered) - 1) * q / 100.0
    low = math.floor(rank)
    high = math.ceil(rank)
    if low == high:
        return ordered[low]
    return ordered[low] + (ordered[high] - ordered[low]) * (rank - low)


def _p95(values: list[float]) -> float | None:
    finite = [v for v in values if math.isfinite(v)]
    return round(percentile(finite, PERCENTILE), 4) if finite else None


def derive(samples: dict[str, list[float]]) -> dict[str, dict[str, float]]:
    """Return `{"baseline_p95": {...}, "ServiceHighLatency": {...}, "KafkaConsumerLagHigh": {...}}`."""
    baseline: dict[str, float] = {}
    latency: dict[str, float] = {}
    lag: dict[str, float] = {}
    for key, values in samples.items():
        kind, _, svc = key.partition(":")
        if kind == "latency_p95" and svc:
            p95 = _p95(values)
            baseline[svc] = p95 if p95 is not None else 0.0
            latency[svc] = max(LATENCY_FLOOR_S, round(LATENCY_FACTOR * baseline[svc], 4))
        elif kind == "kafka_consumer_lag" and svc:
            p95 = _p95(values)
            lag[svc] = max(LAG_FLOOR, round(LAG_FACTOR * p95, 4)) if p95 is not None else LAG_FLOOR
        else:
            raise ValueError(f"unknown sample key: {key!r}")
    return {
        "baseline_p95": dict(sorted(baseline.items())),
        "ServiceHighLatency": dict(sorted(latency.items())),
        "KafkaConsumerLagHigh": dict(sorted(lag.items())),
    }


def render_yaml(thresholds: dict[str, dict[str, float]], date: str) -> str:
    lines = [
        f"# GENERATED by scripts/derive_thresholds.py from the WKL-004 baseline run on {date}. Do not edit."
    ]
    for name, mapping in thresholds.items():
        body = ", ".join(f"{svc}: {value!r}" for svc, value in mapping.items())
        lines.append(f"{name}: {{{body}}}")
    return "\n".join(lines) + "\n"


def _write_both(text: str, targets: list[Path]) -> None:
    """Write `text` to every target; the targets change only after every temporary file was written.

    Step 1 writes `<target>.tmp` next to each target (creating parent directories); a failure while writing
    the temporary files leaves both targets unchanged and removes the temporary files. Step 2 renames each
    temporary file over its target with `Path.replace`; a rename failure after that can leave the first target
    updated, and the run exits 2 and must be repeated.
    """
    temps: list[tuple[Path, Path]] = []
    try:
        for target in targets:
            target.parent.mkdir(parents=True, exist_ok=True)
            tmp = target.with_name(target.name + ".tmp")
            tmp.write_text(text, encoding="utf-8", newline="\n")
            temps.append((tmp, target))
    except OSError:
        for tmp, _ in temps:
            tmp.unlink(missing_ok=True)
        raise
    for tmp, target in temps:
        tmp.replace(target)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0] if __doc__ else None)
    ap.add_argument("--samples", required=True, type=Path)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--chart-copy", type=Path, default=DEFAULT_CHART_COPY)
    args = ap.parse_args(argv)
    try:
        doc: Any = json.loads(args.samples.read_text(encoding="utf-8"))
        samples = {str(k): [float(x) for x in v] for k, v in doc["samples"].items()}
        date = str(doc["date"])
        text = render_yaml(derive(samples), date)
    except (OSError, ValueError, KeyError, TypeError, AttributeError) as exc:
        print(f"derive_thresholds: {exc}", file=sys.stderr)
        return 2
    try:
        _write_both(text, [args.out, args.chart_copy])
    except OSError as exc:
        print(f"derive_thresholds: cannot write the outputs: {exc}", file=sys.stderr)
        return 2
    print(f"derive_thresholds: wrote {args.out} and {args.chart_copy}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
