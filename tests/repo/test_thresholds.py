"""Verifies WKL-031 (thresholds marked with a dagger), WKL-004, WKL-030 (W1-T13)."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
import yaml

from scripts import derive_thresholds
from scripts.derive_thresholds import derive, percentile

REPO = Path(__file__).resolve().parents[2]


def test_latency_threshold_is_max_of_1s_and_3x_p95() -> None:
    """WKL-031: ServiceHighLatency is max(1.0, 3 x baseline p95); KafkaConsumerLagHigh floors at 1000."""
    out = derive(
        {
            "latency_p95:payment": [0.1] * 100,
            "latency_p95:checkout": [0.5] * 100,
            "kafka_consumer_lag:fraud-detection": [10.0] * 100,
        }
    )
    assert out["ServiceHighLatency"]["payment"] == 1.0
    assert out["ServiceHighLatency"]["checkout"] == 1.5
    assert out["KafkaConsumerLagHigh"]["fraud-detection"] == 1000.0


def test_baseline_p95_uses_95th_percentile() -> None:
    """WKL-031: the baseline p95 is the 95th percentile (linear interpolation) rounded to 4 decimals."""
    vals = [float(i) for i in range(1, 101)]
    out = derive({"latency_p95:x": vals})
    assert out["baseline_p95"]["x"] == 95.05


def test_lag_threshold_scales_above_floor() -> None:
    """WKL-031: KafkaConsumerLagHigh is max(1000, 10 x 95th percentile of the lag)."""
    out = derive({"kafka_consumer_lag:fraud-detection": [500.0] * 50})
    assert out["KafkaConsumerLagHigh"]["fraud-detection"] == 5000.0


def test_non_finite_samples_are_ignored_and_empty_series_use_the_floor() -> None:
    """WKL-031: NaN and inf samples (no traffic) are dropped; a service without samples gets the 1.0 floor."""
    nan = float("nan")
    out = derive(
        {"latency_p95:a": [nan, 0.2, float("inf"), 0.2], "latency_p95:b": [nan, nan], "latency_p95:c": []}
    )
    assert out["baseline_p95"] == {"a": 0.2, "b": 0.0, "c": 0.0}
    assert out["ServiceHighLatency"] == {"a": 1.0, "b": 1.0, "c": 1.0}


def test_percentile_matches_linear_interpolation() -> None:
    """WKL-031: `percentile` equals numpy.percentile with the default linear method."""
    assert percentile([1.0, 2.0, 3.0, 4.0], 50) == 2.5
    assert percentile([7.0], 95) == 7.0
    assert percentile([1.0, 2.0], 0) == 1.0
    assert percentile([1.0, 2.0], 100) == 2.0
    with pytest.raises(ValueError):
        percentile([], 95)


def test_unknown_key_prefix_is_rejected() -> None:
    """WKL-031: only `latency_p95:<svc>` and `kafka_consumer_lag:<svc>` keys are accepted."""
    with pytest.raises(ValueError, match="unknown sample key"):
        derive({"cpu_usage:payment": [1.0]})


def test_cli_writes_values_file_and_chart_copy(tmp_path: Path) -> None:
    """WKL-031: the CLI writes deploy/values/alert-thresholds.yaml and an identical chart copy."""
    samples = tmp_path / "samples.json"
    samples.write_text(
        json.dumps(
            {
                "date": "2026-11-28",
                "samples": {
                    "latency_p95:payment": [0.1] * 10,
                    "kafka_consumer_lag:fraud-detection": [0.0] * 10,
                },
            }
        ),
        encoding="utf-8",
    )
    values = tmp_path / "values" / "alert-thresholds.yaml"
    chart = tmp_path / "chart" / "alert-thresholds.yaml"
    assert (
        derive_thresholds.main(["--samples", str(samples), "--out", str(values), "--chart-copy", str(chart)])
        == 0
    )
    text = values.read_text(encoding="utf-8")
    header = "# GENERATED by scripts/derive_thresholds.py from the WKL-004 baseline run on 2026-11-28."
    assert text.startswith(f"{header} Do not edit.\n")
    assert chart.read_text(encoding="utf-8") == text
    doc = yaml.safe_load(text)
    assert doc == {
        "baseline_p95": {"payment": 0.1},
        "ServiceHighLatency": {"payment": 1.0},
        "KafkaConsumerLagHigh": {"fraud-detection": 1000.0},
    }


def test_committed_thresholds_are_consistent() -> None:
    """WKL-031: the two committed copies are identical and every threshold follows the WKL-031 formulas."""
    values = REPO / "deploy/values/alert-thresholds.yaml"
    chart = REPO / "deploy/charts/observability/files/alert-thresholds.yaml"
    assert values.read_text(encoding="utf-8") == chart.read_text(encoding="utf-8")
    doc = yaml.safe_load(values.read_text(encoding="utf-8"))
    assert set(doc) == {"baseline_p95", "ServiceHighLatency", "KafkaConsumerLagHigh"}
    for svc, base in doc["baseline_p95"].items():
        assert doc["ServiceHighLatency"][svc] == max(1.0, round(3 * base, 4))
    assert set(doc["ServiceHighLatency"]) == set(doc["baseline_p95"])
    assert set(doc["KafkaConsumerLagHigh"]) == {"fraud-detection"}
    assert doc["KafkaConsumerLagHigh"]["fraud-detection"] >= 1000.0


def test_cli_exits_2_and_changes_nothing_when_an_output_cannot_be_written(tmp_path: Path) -> None:
    """WKL-031: an OSError while writing exits 2; the first target is not left half written."""
    samples = tmp_path / "samples.json"
    samples.write_text(
        json.dumps({"date": "2026-11-28", "samples": {"latency_p95:payment": [0.1] * 5}}), encoding="utf-8"
    )
    values = tmp_path / "values" / "alert-thresholds.yaml"
    blocker = tmp_path / "blocker"
    blocker.write_text("a file, not a directory", encoding="utf-8")
    chart = blocker / "alert-thresholds.yaml"  # parent is a file: mkdir raises OSError
    code = derive_thresholds.main(
        ["--samples", str(samples), "--out", str(values), "--chart-copy", str(chart)]
    )
    assert code == 2
    assert not values.exists()
    assert not list((tmp_path / "values").glob("*.tmp"))


def test_cli_exits_2_on_malformed_samples(tmp_path: Path) -> None:
    """WKL-031: a samples file without `samples` exits 2 and writes nothing."""
    samples = tmp_path / "samples.json"
    samples.write_text("{}", encoding="utf-8")
    out = tmp_path / "out.yaml"
    assert (
        derive_thresholds.main(["--samples", str(samples), "--out", str(out), "--chart-copy", str(out)]) == 2
    )
    assert not out.exists()
